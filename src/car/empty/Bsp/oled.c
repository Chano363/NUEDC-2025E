/* ── 显存（页寻址模式）── */
static uint8_t g_oled_buffer[OLED_PAGES][OLED_WIDTH];
static uint8_t g_oled_address = OLED_I2C_ADDR;

/*
 * Open-drain software I2C using the MSPM0 GPIO Hi-Z output feature, following
 * TI's gpio_toggle_output_hiz DriverLib example.  With Hi-Z enabled, writing
 * one releases the line and writing zero actively pulls it low.
 */
static void I2C_Delay(void)
{
    delay_us(5);
}

static void SCL_Low(void)
{
    DL_GPIO_clearPins(OLED_SW_I2C_PORT, OLED_SW_I2C_SCL_PIN);
}

static void SCL_Release(void)
{
    DL_GPIO_setPins(OLED_SW_I2C_PORT, OLED_SW_I2C_SCL_PIN);
}

static void SDA_Low(void)
{
    DL_GPIO_clearPins(OLED_SW_I2C_PORT, OLED_SW_I2C_SDA_PIN);
}

static void SDA_Release(void)
{
    DL_GPIO_setPins(OLED_SW_I2C_PORT, OLED_SW_I2C_SDA_PIN);
}

static void I2C_Start(void)
{
    SDA_Release();
    I2C_Delay();
    SCL_Release();
    I2C_Delay();
    SDA_Low();
    I2C_Delay();
    SCL_Low();
    I2C_Delay();
}

static void I2C_Stop(void)
{
    SDA_Low();
    I2C_Delay();
    SCL_Release();
    I2C_Delay();
    SDA_Release();
    I2C_Delay();
}

/* Same as the gimbal routine: generate the ACK clock but do not gate writes. */
static void I2C_SendByte(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++) {
        if ((data & 0x80U) != 0U) {
            SDA_Release();
        } else {
            SDA_Low();
        }
        I2C_Delay();
        SCL_Release();
        I2C_Delay();
        SCL_Low();
        I2C_Delay();
        data <<= 1;
    }

    SDA_Release();
    I2C_Delay();
    SCL_Release();
    I2C_Delay();
    SCL_Low();
    I2C_Delay();
}

/* Exact transaction shape used by the working gimbal OLED driver. */
static void OLED_Write(uint8_t address, uint8_t type, uint8_t data)
{
    I2C_Start();
    I2C_SendByte((uint8_t)(address << 1));
    I2C_SendByte(type);
    I2C_SendByte(data);
    I2C_Stop();
}

static void OLED_WriteCmd(uint8_t cmd)
{
    OLED_Write(g_oled_address, OLED_CMD_BYTE, cmd);
}

static void OLED_WriteData(uint8_t data)
{
    OLED_Write(g_oled_address, OLED_DATA_BYTE, data);
}

/* ── 设置页地址和列地址 ── */
static void OLED_SetPos(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 + page);                  /* 页地址 0~7 */
    OLED_WriteCmd(0x00 + (col & 0x0F));          /* 列低 4 位 */
    OLED_WriteCmd(0x10 + ((col >> 4) & 0x0F));   /* 列高 4 位 */
}

/* ── 初始化序列（SSD1306）── */
void OLED_Init(void)
{
    /* Outputs stay enabled.  SET means Hi-Z because SysConfig enables HIZ. */
    DL_GPIO_enableOutput(OLED_SW_I2C_PORT,
        OLED_SW_I2C_SCL_PIN | OLED_SW_I2C_SDA_PIN);
    SCL_Release();
    SDA_Release();

    delay_ms(200);   /* SSD1306 power-on stabilization */

    /* Same fixed address and initialization sequence as the gimbal. */
    g_oled_address = OLED_I2C_ADDR;
    OLED_WriteCmd(0xAE);   /* display off */
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x02);
    OLED_WriteCmd(0xA1);
    OLED_WriteCmd(0xC8);
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x30);
    OLED_WriteCmd(0xA4);
    OLED_WriteCmd(0xA6);
    OLED_WriteCmd(0xAF);

    OLED_Clear();
    OLED_Refresh();
}

void OLED_Clear(void)
{
    memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
}

void OLED_ShowString(uint8_t row, uint8_t col, const char *str)
{
    if (row >= OLED_PAGES || col >= 21) return;

    uint8_t start_col = col * 6;
    uint8_t *page = g_oled_buffer[row];

    while (*str && col < 21) {
        uint8_t ch = (uint8_t)*str;
        if (ch < 0x20 || ch > 0x7E) ch = 0x20;
        const uint8_t *glyph = font6x8[ch - 0x20];
        for (uint8_t i = 0; i < 6; i++) {
            page[start_col + i] = glyph[i];
        }
        start_col += 6;
        col++;
        str++;
    }
}

void OLED_ShowInt(uint8_t row, uint8_t col, int32_t num)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%ld", (long)num);
    OLED_ShowString(row, col, buf);
}

void OLED_Refresh(void)
{
    for (uint8_t p = 0; p < OLED_PAGES; p++) {
        OLED_SetPos(p, 0);
        for (uint8_t col = 0; col < OLED_WIDTH; col++) {
            OLED_WriteData(g_oled_buffer[p][col]);
        }
    }
}
